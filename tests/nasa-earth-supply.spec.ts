import { test, expect } from "@playwright/test";
import { createClient } from "@supabase/supabase-js";
import { login } from "./helpers";
import { assertIsolatedTestEnvironment } from "./isolation";
import { getReportingSupply } from "../src/lib/edition/news-supply";
import { getOrCreateDailyEdition } from "../src/lib/edition/service";
import { getArchivedEditionById } from "../src/lib/edition/archive";
import { generateEditionPdf } from "../src/lib/edition/pdf";
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

test("NASA Earth adds credited text through trusted supply and is excluded when AI is enabled", async ({ context, page, baseURL }, testInfo) => {
  assertIsolatedTestEnvironment(process.env);
  const reader = await login("A", context, baseURL!);
  const readerId = (await reader.auth.getUser()).data.user!.id;
  let editionId: string | undefined;
  const server = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_REPORTING_SERVICE_KEY!, { auth: { persistSession: false, autoRefreshToken: false } });
  const previous = await server.from("reporting_cache_meta").select("*").eq("id", "news_supply").maybeSingle();
  expect(previous.error).toBeNull();
  const flags = ["NASA_EARTH_ENABLED", "NASA_EARTH_PUBLIC_REPORTING_ENABLED", "GEMINI_AI_EDITOR_ENABLED", "GEMINI_PUBLIC_BRIEFINGS_ENABLED"];
  const originalFlags = flags.map(name => process.env[name]);
  const originalFetch = globalThis.fetch;
  const now = new Date();
  const root = "https://science.nasa.gov/earth/earth-observatory/";
  const body = "Researchers tracked changes in Pacific Ocean temperatures using satellite measurements. The observations show how warmer water moves across the ocean and changes regional weather patterns. The team compared measurements over several years to understand the developing climate pattern.";
  const item = (slug: string, text: string, domain = root) => `<item><title>Satellite observations track changing Pacific Ocean temperatures</title><link>${domain}${slug}/</link><pubDate>${now.toUTCString()}</pubDate><content:encoded><![CDATA[<nav>Navigation must not become reporting</nav><figure><p class="wp-block-paragraph">Excluded media caption</p></figure><p class="wp-block-paragraph">${text}</p><p class="wp-block-paragraph"><em>NASA Earth Observatory. Story by Controlled Author.</em></p>]]></content:encoded></item>`;
  globalThis.fetch = async (input, init) => String(input) === "https://www.nasa.gov/feed/" ? new Response(`<rss version="2.0"><channel><language>en-US</language>${item("controlled-earth-recovery", body)}${item("controlled-earth-restricted", body + " All rights reserved.")}${item("controlled-earth-copyright", body + " &#169; Other Publisher 2026.")}${item("controlled-earth-outside", body, "https://www.nasa.gov/missions/")}</channel></rss>`) : originalFetch(input, init);
  process.env.NASA_EARTH_ENABLED = "true";
  process.env.NASA_EARTH_PUBLIC_REPORTING_ENABLED = "true";
  process.env.GEMINI_AI_EDITOR_ENABLED = "false";
  process.env.GEMINI_PUBLIC_BRIEFINGS_ENABLED = "false";
  try {
    expect((await server.from("reporting_cache_meta").delete().eq("id", "news_supply")).error).toBeNull();
    const supply = await getReportingSupply(reader, { referenceDate: now, reportingWriter: server, forceRefresh: true });
    const nasa = supply.filter(a => a.raw_data?.provider === "nasa-earth");
    expect(nasa).toHaveLength(1);
    expect(nasa[0].description).toBe(body);
    expect(nasa[0].image_url).toBeNull();
    expect(nasa[0].raw_data?.source_attribution).toMatchObject({ authors: ["Controlled Author"], license: "NASA Earth reuse policy", license_url: "https://science.nasa.gov/earth/faq/" });
    const result = await getOrCreateDailyEdition(reader, readerId, { controlledDate: "2026-08-19", referenceDate: now, reportingWriter: server });
    expect(result.success).toBe(true);
    if (!result.success) return;
    editionId = result.edition.id;
    expect(result.edition.stories.some(story => story.source_article_id === nasa[0].id)).toBe(true);
    await page.goto(`/archive/${editionId}`);
    await expect(page.locator(".source-attribution").filter({ hasText: "NASA Earth reuse policy" })).toContainText("Controlled Author");
    const archived = await getArchivedEditionById(reader, readerId, editionId);
    expect(archived).not.toBeNull();
    if (!archived) return;
    const pdfPath = testInfo.outputPath("nasa-earth.pdf");
    writeFileSync(pdfPath, await generateEditionPdf(archived));
    const pdf = JSON.parse(execFileSync(process.env.HERALD_TEST_PYTHON || "python", [resolve("scripts/inspect-pdf.py"), pdfPath], { encoding: "utf8" }));
    expect(pdf.full_text).toContain("Controlled Author");
    expect(pdf.links).toContain("https://science.nasa.gov/earth/faq/");
    process.env.GEMINI_AI_EDITOR_ENABLED = "true";
    expect((await getReportingSupply(reader, { referenceDate: now })).some(a => a.raw_data?.provider === "nasa-earth")).toBe(false);
    process.env.GEMINI_AI_EDITOR_ENABLED = "false";
    process.env.GEMINI_PUBLIC_BRIEFINGS_ENABLED = "true";
    expect((await getReportingSupply(reader, { referenceDate: now })).some(a => a.raw_data?.provider === "nasa-earth")).toBe(false);
    expect(await getArchivedEditionById(reader, readerId, editionId)).toEqual(archived);
  } finally {
    globalThis.fetch = originalFetch;
    flags.forEach((name, i) => { if (originalFlags[i] === undefined) delete process.env[name]; else process.env[name] = originalFlags[i]; });
    if (editionId) expect((await reader.from("editions").delete().eq("id", editionId).eq("reader_id", readerId)).error).toBeNull();
    expect((await server.from("source_articles").delete().like("external_id", "nasa-earth:%controlled-earth-%")).error).toBeNull();
    expect((await server.from("reporting_cache_meta").delete().eq("id", "news_supply")).error).toBeNull();
    if (previous.data) expect((await server.from("reporting_cache_meta").insert(previous.data)).error).toBeNull();
  }
});
